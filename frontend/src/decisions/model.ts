/* Existing decision_flow.py contract. No new stage transitions are inferred here. */
export type Stage = 'draft' | 'positions' | 'critique' | 'proposal' | 'verdicts' | 'review' | 'recorded' | 'stopped';
export interface Contribution {
  id: string; author: string; stage: Stage; kind: string; revision: number; epoch: number; created: number;
  text?: string; context?: 'fresh' | 'prior'; before_new_direction?: boolean;
  evidence?: string[]; responds_to?: string[]; proposal_id?: string; verdict?: 'agree' | 'dissent'; reason?: string;
  agreed?: string[]; dissent?: {point: string; by: string[]}[]; unresolved?: string[]; would_change?: string[];
  answers?: {challenge_id: string; status: string; note: string}[];
  tasks?: {title: string; details: string}[];
  round?: number; sealed?: boolean; attachments?: {url: string; name?: string}[];
}
export interface Summary {
  id: string; question: string; stage: Stage; channel: string; participants: string[]; lead: string;
  updated: number; interrupted: string; outcome: 'agreed' | 'dissent' | 'unresolved';
}
export interface Decision extends Summary {
  round?: number; in_place?: boolean; origin?: [string, number]; task_id?: string;
  phase?: 'draft' | 'discussing' | 'candidate' | 'review_ready' | 'recorded' | 'stopped';
  coverage?: {submitted: string[]; invited: string[]; missing: string[]};
  inputs?: {quote: string; kind: 'requirement' | 'suggestion'; message_id: number; author: string}[];
  rounds?: {round: number; revealed: boolean; concluded: boolean; outcome: string; proposal_id: string; reason: string}[];
  criteria: string[]; revision: number; epoch: number; returns_used: number; edits_used: number; deadline?: number;
  contributions: Contribution[]; superseded?: string[];
  turns: Record<string, {state: 'queued' | 'no_response' | 'submitted'; detail?: string}>;
  record: {key?: string; note_id?: string; tasks?: {title: string; details: string; id?: string; error?: string}[]};
  token: {id: string; stage: Stage; revision: number; epoch: number}; owed: string[];
  current_proposal: string; unanswered_challenges?: string[]; actions: string[];
}
export interface Listing {decisions: Summary[]; available: string[]; chat_slots?: {used: number; limit: number}}
export interface Draft {question: string; criteria: string; participants: string[]; lead: string}
export const stages = ['Question and criteria', 'Initial positions', 'Challenge and response', 'Team proposal', 'Your decision'];
export const stageIndex: Record<Stage, number> = {draft: 0, positions: 1, critique: 2, proposal: 3, verdicts: 4, review: 4, recorded: 4, stopped: 4};
export const contextLabel = (context?: string) => context === 'fresh' ? 'Fresh session' : context === 'prior' ? 'Prior debate in context' : 'Context not reported';
export const proposalFor = (d: Decision) => d.contributions.find(c => c.id === d.current_proposal);
export function votesFor(d: Decision) {
  return Object.fromEntries(d.contributions.filter(c => c.kind === 'verdict' && c.proposal_id === d.current_proposal && c.epoch === d.epoch).map(c => [c.author, c]));
}

/** Match the bounded note generated by DecisionFlow.record, including its visible truncation. */
export function notePreview(d: Decision): string {
  const proposal = proposalFor(d), votes = votesFor(d);
  const lines = [`Team decision ${d.id} recorded by the user (${d.outcome}): ${d.question}`];
  if (proposal) {
    lines.push(`Proposal ${proposal.id} (revision ${d.revision}, by ${proposal.author}): ${proposal.text}`);
    if (proposal.agreed?.length) lines.push('Agreed: ' + proposal.agreed.join('; '));
    if (proposal.unresolved?.length) lines.push('Unresolved: ' + proposal.unresolved.join('; '));
  }
  for (const name of d.participants) {
    const position = [...d.contributions].reverse().find(c => c.kind === 'position' && c.author === name && !d.superseded?.includes(c.id));
    const skipped = [...new Set(d.contributions.filter(c => c.kind === 'missing' && c.author === name).map(c => c.stage))];
    const facts = [position ? `first answer: ${position.context ? contextLabel(position.context) : 'unknown context'}` : 'no first answer'];
    if (skipped.length) facts.push('skipped: ' + skipped.join(', '));
    const vote = votes[name];
    lines.push(`${name} (${facts.join('; ')}): ${vote ? `${vote.verdict}, ${vote.reason}` : 'no verdict'}`);
  }
  lines.push('Grants no deploy, restart, settings or credential authority.');
  const note = lines.join('\n');
  // Python slices code points; spreading preserves that boundary for non-BMP characters too.
  return [...note].length > 4000 ? [...note].slice(0, 3940).join('') + ` [...] (full record: decision ${d.id})` : note;
}

export function decisionURL(id: string) {
  const url = new URL(location.href);
  url.searchParams.set('view', 'board'); url.searchParams.set('decision', id); url.searchParams.delete('task');
  url.searchParams.delete('history'); url.searchParams.delete('project');
  return url.pathname + url.search;
}
export function openDecision(id: string) {
  history.pushState({}, '', decisionURL(id)); window.dispatchEvent(new PopStateEvent('popstate'));
}
